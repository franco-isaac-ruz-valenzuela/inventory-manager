const normalizeProductText = text =>
  String(text ?? '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/,/g, '.')
    .replace(/\s+/g, ' ')
    .trim()
    .toUpperCase();

const PRICE_BY_NORMALIZED_NAME = new Map(
  Object.entries(PRODUCT_PRICE_LIST).map(([sku, entry]) => [
    normalizeProductText(entry.name),
    { sku, ...entry },
  ])
);

export function lookupProductPrice(sku, name = '') {
  const key = String(sku ?? '').trim().toUpperCase();
  if (key) {
    if (PRODUCT_PRICE_LIST[key]) return PRODUCT_PRICE_LIST[key];
    const unpadded = key.replace(/^0+/, '');
    if (unpadded && PRODUCT_PRICE_LIST[unpadded]) return PRODUCT_PRICE_LIST[unpadded];
  }
  const normName = normalizeProductText(name);
  if (normName && PRICE_BY_NORMALIZED_NAME.has(normName)) {
    return PRICE_BY_NORMALIZED_NAME.get(normName);
  }
  return null;
}
